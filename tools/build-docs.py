"""
Сборка PDF-документов проекта «Смена контента».

Что создаётся (в assets/docs/):
  press-kit.pdf                — пресс-кит для партнёров и грантовых заявок
  polozhenie-o-redakcii.pdf    — положение о редакции
  pamyatka-avtoru.pdf          — памятка автору
  programma-mediashkoly.pdf    — программа медиашколы
  soglasie-na-publikaciyu.pdf  — форма согласия на публикацию

Запуск:  python3 tools/build-docs.py
Нужен пакет reportlab:  pip install reportlab
Шрифты: DejaVu (обычно лежат в системе) — поддерживают кириллицу.
"""

import os
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib import colors
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.enums import TA_LEFT
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (
    BaseDocTemplate, PageTemplate, Frame, Paragraph, Spacer, Table,
    TableStyle, KeepTogether, HRFlowable, PageBreak,
)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "assets", "docs")
os.makedirs(OUT, exist_ok=True)

FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/dejavu/DejaVuSans.ttf",
]
BOLD_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf",
]
MONO_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf",
    "/usr/share/fonts/dejavu/DejaVuSansMono.ttf",
]


def first_existing(paths):
    for p in paths:
        if os.path.exists(p):
            return p
    raise SystemExit("Не найден шрифт DejaVu. Установите пакет fonts-dejavu.")


pdfmetrics.registerFont(TTFont("D", first_existing(FONT_CANDIDATES)))
pdfmetrics.registerFont(TTFont("DB", first_existing(BOLD_CANDIDATES)))
pdfmetrics.registerFont(TTFont("DM", first_existing(MONO_CANDIDATES)))
pdfmetrics.registerFontFamily("D", normal="D", bold="DB", italic="D", boldItalic="DB")
pdfmetrics.registerFontFamily("DB", normal="DB", bold="DB", italic="DB", boldItalic="DB")

INK = colors.HexColor("#14130f")
ACCENT = colors.HexColor("#ff3d14")
MUTED = colors.HexColor("#797464")
LINE = colors.HexColor("#d8d3c5")

S = {
    "kicker": ParagraphStyle("kicker", fontName="DM", fontSize=7.5, leading=11,
                             textColor=ACCENT, spaceAfter=6),
    "h1": ParagraphStyle("h1", fontName="DB", fontSize=25, leading=28,
                         textColor=INK, spaceAfter=8),
    "h2": ParagraphStyle("h2", fontName="DB", fontSize=12.5, leading=16,
                         textColor=INK, spaceBefore=14, spaceAfter=5),
    "h3": ParagraphStyle("h3", fontName="DB", fontSize=10, leading=13,
                         textColor=INK, spaceBefore=8, spaceAfter=3),
    "p": ParagraphStyle("p", fontName="D", fontSize=9.8, leading=14.6,
                        textColor=INK, spaceAfter=7, alignment=TA_LEFT),
    "lead": ParagraphStyle("lead", fontName="D", fontSize=11, leading=16,
                           textColor=colors.HexColor("#403d34"), spaceAfter=10),
    "small": ParagraphStyle("small", fontName="D", fontSize=8.2, leading=11.5,
                            textColor=MUTED, spaceAfter=4),
    "li": ParagraphStyle("li", fontName="D", fontSize=9.6, leading=14,
                         textColor=INK, leftIndent=10, bulletIndent=0, spaceAfter=3),
    "quote": ParagraphStyle("quote", fontName="D", fontSize=10.2, leading=15,
                            textColor=INK, leftIndent=12, spaceAfter=8, spaceBefore=4),
    "cell": ParagraphStyle("cell", fontName="D", fontSize=8.6, leading=12, textColor=INK),
    "cellb": ParagraphStyle("cellb", fontName="DB", fontSize=8.6, leading=12, textColor=INK),
}


class Doc:
    def __init__(self, filename, kicker, title, subtitle, header_right=""):
        self.path = os.path.join(OUT, filename)
        self.kicker = kicker
        self.title = title
        self.subtitle = subtitle
        self.header_right = header_right or kicker.split(" · ")[0]
        self.items = []

    def _frame(self, canvas, doc):
        w, h = A4
        canvas.saveState()
        canvas.setFillColor(INK)
        canvas.setFont("DM", 7.2)
        canvas.drawString(22 * mm, h - 16 * mm, "СМЕНА КОНТЕНТА")
        canvas.setFillColor(MUTED)
        canvas.drawRightString(w - 22 * mm, h - 16 * mm, self.header_right)
        canvas.setStrokeColor(ACCENT)
        canvas.setLineWidth(1)
        canvas.line(22 * mm, h - 18.5 * mm, w - 22 * mm, h - 18.5 * mm)

        canvas.setStrokeColor(LINE)
        canvas.setLineWidth(0.6)
        canvas.line(22 * mm, 17 * mm, w - 22 * mm, 17 * mm)
        canvas.setFillColor(MUTED)
        canvas.setFont("DM", 6.8)
        canvas.drawString(22 * mm, 12.5 * mm,
                          "Молодёжное медиа · медиашкола · сообщество авторов")
        canvas.drawRightString(w - 22 * mm, 12.5 * mm, "стр. %d" % canvas.getPageNumber())
        canvas.restoreState()

    def add(self, *flowables):
        for f in flowables:
            self.items.append(f)

    def h1(self, text):
        self.add(Paragraph(text, S["h1"]))

    def h2(self, text):
        self.add(Paragraph(text, S["h2"]))

    def h3(self, text):
        self.add(Paragraph(text, S["h3"]))

    def p(self, text, style="p"):
        self.add(Paragraph(text, S[style]))

    def bullets(self, items):
        for it in items:
            self.add(Paragraph(it, S["li"], bulletText="—"))

    def quote(self, text):
        self.add(Spacer(1, 2), Paragraph(text, S["quote"]), Spacer(1, 4))

    def rule(self, space_before=6, space_after=8):
        self.add(Spacer(1, space_before),
                 HRFlowable(width="100%", thickness=0.7, color=LINE),
                 Spacer(1, space_after))

    def table(self, rows, widths=None):
        data = []
        for i, row in enumerate(rows):
            style = "cellb" if i == 0 else "cell"
            data.append([Paragraph(str(c), S[style]) for c in row])
        t = Table(data, colWidths=widths or [55 * mm, 110 * mm], hAlign="LEFT", repeatRows=1)
        t.setStyle(TableStyle([
            ("LINEBELOW", (0, 0), (-1, 0), 0.8, INK),
            ("LINEBELOW", (0, 1), (-1, -1), 0.5, LINE),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING", (0, 0), (0, -1), 0),
        ]))
        self.add(t, Spacer(1, 8))

    def form_lines(self, labels, width=120 * mm):
        for label in labels:
            row = Table([[Paragraph(label, S["cell"]), ""]],
                        colWidths=[62 * mm, width - 62 * mm], hAlign="LEFT")
            row.setStyle(TableStyle([
                ("LINEBELOW", (1, 0), (1, 0), 0.6, INK),
                ("TOPPADDING", (0, 0), (-1, -1), 9),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("LEFTPADDING", (0, 0), (0, -1), 0),
            ]))
            self.add(row)

    def build(self):
        doc = BaseDocTemplate(
            self.path, pagesize=A4,
            leftMargin=22 * mm, rightMargin=22 * mm,
            topMargin=24 * mm, bottomMargin=22 * mm,
            title=self.title, author="Смена контента",
            subject=self.kicker,
        )
        frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="main")
        doc.addPageTemplates([PageTemplate(id="all", frames=[frame], onPage=self._frame)])

        head = [
            Paragraph(self.kicker, S["kicker"]),
            Paragraph(self.title, S["h1"]),
        ]
        if self.subtitle:
            head.append(Paragraph(self.subtitle, S["lead"]))
        head.append(Spacer(1, 4))
        doc.build(head + self.items)
        print("готово:", os.path.relpath(self.path, ROOT))


