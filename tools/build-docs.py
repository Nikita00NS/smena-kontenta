class Doc:
    def __init__(self, filename, kicker, title, subtitle, header_right="", plain=False):
        self.path = os.path.join(OUT, filename)
        self.kicker = kicker
        self.plain = plain
        self.title = title
        self.subtitle = subtitle
        self.header_right = header_right or kicker.split(" · ")[0]
        self.header_left = (title if plain else "").upper()
        self.items = []

    def _frame(self, canvas, doc):
        w, h = A4
        canvas.saveState()
        if self.plain:
            """Официальные документы печатаются без логотипа и цветных плашек:
            сверху только название документа и номер страницы, как в бланках."""
            canvas.setFillColor(INK)
            canvas.setFont("DM", 7.4)
            canvas.drawString(22 * mm, h - 15 * mm, self.header_left)
            canvas.setStrokeColor(colors.black)
            canvas.setLineWidth(0.5)
            canvas.line(22 * mm, h - 17.5 * mm, w - 22 * mm, h - 17.5 * mm)
            canvas.setFillColor(INK)
            canvas.setFont("DM", 7.2)
            canvas.drawCentredString(w / 2.0, 12 * mm, "— %d —" % canvas.getPageNumber())
            canvas.restoreState()
            return
        logo = os.path.join("assets", "img", "logo-dark.png")
        if os.path.exists(logo):
            from reportlab.platypus import Image as RLImage
            lh = 5.0 * mm
            lw = lh * 1706 / 309
            canvas.drawImage(logo, 22 * mm, h - 19.2 * mm, width=lw, height=lh,
                             mask="auto")
            canvas.setFont("DM", 7.2)
        else:
            canvas.setFillColor(INK)
            canvas.setFont("DM", 7.2)
            canvas.drawString(22 * mm, h - 16 * mm, "СМЕНА КОНТЕНТА")
        canvas.setFillColor(MUTED)
        canvas.drawRightString(w - 22 * mm, h - 16.4 * mm, self.header_right)
        canvas.setStrokeColor(ACCENT)
        canvas.setLineWidth(1)
        canvas.line(22 * mm, h - 21.4 * mm, w - 22 * mm, h - 21.4 * mm)

        canvas.setStrokeColor(LINE)
        canvas.setLineWidth(0.6)
        canvas.line(22 * mm, 17 * mm, w - 22 * mm, 17 * mm)
        canvas.setFillColor(MUTED)
        canvas.setFont("DM", 6.8)
        canvas.drawString(22 * mm, 12.5 * mm,
                          "Молодёжное медиа · медиашкола · сообщество авторов")
        canvas.drawRightString(w - 22 * mm, 12.5 * mm, "стр. %d" % canvas.getPageNumber())
        canvas.restoreState()

    def add(self, *flowables):
        for f in flowables:
            self.items.append(f)

    def h1(self, text):
        self.add(Paragraph(text, S["h1"]))

    def h2(self, text):
        self.add(Paragraph(text, S["h2"]))

    def h3(self, text):
        self.add(Paragraph(text, S["h3"]))

    def p(self, text, style="p"):
        self.add(Paragraph(text, S[style]))

    def bullets(self, items):
        for it in items:
            self.add(Paragraph(it, S["li"], bulletText="—"))

    def quote(self, text):
        self.add(Spacer(1, 2), Paragraph(text, S["quote"]), Spacer(1, 4))

    def rule(self, space_before=6, space_after=8):
        self.add(Spacer(1, space_before),
                 HRFlowable(width="100%", thickness=0.7, color=LINE),
                 Spacer(1, space_after))

    def table(self, rows, widths=None):
        data = []
        for i, row in enumerate(rows):
            style = "cellb" if i == 0 else "cell"
            data.append([Paragraph(str(c), S[style]) for c in row])
        t = Table(data, colWidths=widths or [55 * mm, 110 * mm], hAlign="LEFT", repeatRows=1)
        t.setStyle(TableStyle([
            ("LINEBELOW", (0, 0), (-1, 0), 0.8, INK),
            ("LINEBELOW", (0, 1), (-1, -1), 0.5, LINE),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING", (0, 0), (0, -1), 0),
        ]))
        self.add(t, Spacer(1, 8))

    def form_lines(self, labels, width=120 * mm):
        for label in labels:
            row = Table([[Paragraph(label, S["cell"]), ""]],
                        colWidths=[62 * mm, width - 62 * mm], hAlign="LEFT")
            row.setStyle(TableStyle([
                ("LINEBELOW", (1, 0), (1, 0), 0.6, INK),
                ("TOPPADDING", (0, 0), (-1, -1), 9),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("LEFTPADDING", (0, 0), (0, -1), 0),
            ]))
            self.add(row)

    def build(self):
        doc = BaseDocTemplate(
            self.path, pagesize=A4,
            leftMargin=22 * mm, rightMargin=22 * mm,
            topMargin=24 * mm, bottomMargin=22 * mm,
            title=self.title, author="Смена контента",
            subject=self.kicker,
        )
        frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="main")
        doc.addPageTemplates([PageTemplate(id="all", frames=[frame], onPage=self._frame)])

        head = []
        if not self.plain:
            head.append(Paragraph(self.kicker, S["kicker"]))
        else:
            head.append(Paragraph("УТВЕРЖДЕНО проектом «Смена контента»".replace(
                "УТВЕРЖДЕНО проектом", "Документ проекта"), S["small"]))
        head.append(Paragraph(self.title, S["h1"]))
        if self.subtitle:
            head.append(Paragraph(self.subtitle, S["lead"]))
        head.append(Spacer(1, 4))
        doc.build(head + self.items)
        print("готово:", os.path.relpath(self.path, ROOT))


