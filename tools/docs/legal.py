def _head(d, title, subtitle):
    """Шапка бланка: слева — название документа, справа — кому он адресован."""
    lines = ["Оператору персональных данных —", "<b>%s</b>," % OPERATOR["dative"],
             OPERATOR.get("roleDative", OPERATOR["role"])]
    if OPERATOR.get("address"):
        lines.append("адрес: %s" % OPERATOR["address"])
    lines.append("электронная почта: %s" % PD_MAIL)
    left = [Paragraph(title, S["form_title"]), Paragraph(subtitle, S["form_sub"])]
    t = Table([[left, Paragraph("<br/>".join(lines), S["form_to"])]],
              colWidths=[100 * mm, 78 * mm], hAlign="LEFT")
    t.setStyle(TableStyle([("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (0, 0), 14),
                           ("RIGHTPADDING", (1, 0), (1, 0), 0), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                           ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0)]))
    d.add(t, Spacer(1, 5), HRFlowable(width="100%", thickness=0.6, color=INK), Spacer(1, 3))


