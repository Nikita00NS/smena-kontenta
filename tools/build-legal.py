class NumberedCanvas(pdfcanvas.Canvas):
    """Нумерация вида «стр. 2 из 4»: общее число страниц известно только
    после сборки, поэтому страницы откладываются и нумеруются в конце."""

    def __init__(self, *args, **kwargs):
        pdfcanvas.Canvas.__init__(self, *args, **kwargs)
        self._saved = []

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved)
        for state in self._saved:
            self.__dict__.update(state)
            self.setFont("D", 7)
            self.setFillColor(GREY)
            self.drawRightString(A4[0] - 20 * mm, 11.5 * mm,
                                 "стр. %d из %d" % (self._pageNumber, total))
            pdfcanvas.Canvas.showPage(self)
        pdfcanvas.Canvas.save(self)


class LegalDoc:
    def __init__(self, filename, title, subtitle=""):
        self.path = os.path.join(OUT, filename)
        self.title = title
        self.subtitle = subtitle
        self.items = []

    def add(self, *flow):
        self.items.extend(flow)

    def h2(self, text):
        self.add(Paragraph(text, S["h2"]))

    def p(self, text):
        self.add(Paragraph(text, S["p"]))

    def li(self, items):
        for it in items:
            self.add(Paragraph(it, S["li"], bulletText="—"))

    def table(self, rows, widths):
        data = [[Paragraph(str(c), S["cellb"] if i == 0 else S["cell"]) for c in row]
                for i, row in enumerate(rows)]
        t = Table(data, colWidths=widths, hAlign="LEFT", repeatRows=1)
        t.setStyle(TableStyle([
            ("LINEBELOW", (0, 0), (-1, 0), 0.8, INK),
            ("LINEBELOW", (0, 1), (-1, -1), 0.4, LINE),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
            ("LEFTPADDING", (0, 0), (0, -1), 0),
        ]))
        self.add(t, Spacer(1, 8))

    def signature_lines(self, labels):
        for label in labels:
            row = Table([[Paragraph(label, S["cell"]), ""]],
                        colWidths=[65 * mm, 98 * mm], hAlign="LEFT")
            row.setStyle(TableStyle([
                ("LINEBELOW", (1, 0), (1, 0), 0.7, INK),
                ("TOPPADDING", (0, 0), (-1, -1), 10),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ("LEFTPADDING", (0, 0), (0, -1), 0),
            ]))
            self.add(row)

    def build(self, approved_by=None):
        doc = BaseDocTemplate(
            self.path, pagesize=A4,
            leftMargin=20 * mm, rightMargin=20 * mm,
            topMargin=18 * mm, bottomMargin=20 * mm,
            title=self.title, author="", subject=self.title, creator="",
        )
        frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="main")
        doc.addPageTemplates([PageTemplate(id="all", frames=[frame])])

        head = []
        if approved_by:
            """Гриф утверждения — правый верхний угол, как на официальном документе."""
            t = Table([[Paragraph(
                "УТВЕРЖДЕНО<br/>%s<br/>_____________ /%s/<br/>«____» ____________ 2026 г."
                % (approved_by[0], approved_by[1]), S["cell"])]],
                colWidths=[70 * mm], hAlign="RIGHT")
            t.setStyle(TableStyle([
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 0),
                ("TOPPADDING", (0, 0), (-1, -1), 0),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ]))
            head.append(t)
        head += [
            Paragraph(self.title, S["title"]),
            Paragraph("Действует с %s" % DATE, S["sub"]),
        ]
        doc.build(head + self.items, canvasmaker=NumberedCanvas)
        print("готово:", os.path.relpath(self.path, ROOT))


