def card_blank():
    """Бланк пресс-карты размером с банковскую карту: печатается на плотной
    бумаге, поля заполняются от руки при выдаче."""
    from reportlab.platypus import Image as RLImage

    path = os.path.join(OUT, "blank-press-karty.pdf")
    w, h = 85.6 * mm, 54 * mm
    doc = BaseDocTemplate(path, pagesize=(w, h),
                          leftMargin=6 * mm, rightMargin=6 * mm,
                          topMargin=4.5 * mm, bottomMargin=4 * mm,
                          title="Бланк пресс-карты", author=PROJECT)
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="card")
    doc.addPageTemplates([PageTemplate(id="card", frames=[frame])])

    tiny = ParagraphStyle("t", fontName="D", fontSize=4.8, leading=6, textColor=GREY)
    field = ParagraphStyle("f", fontName="D", fontSize=4.6, leading=6, textColor=INK)
    title = ParagraphStyle("ti", fontName="DB", fontSize=9, leading=11, textColor=INK)
    foot = ParagraphStyle("fo", fontName="D", fontSize=4.2, leading=5.4, textColor=GREY)

    logo = os.path.join(ROOT, "assets", "img", "logo-dark.png")
    top = []
    if os.path.exists(logo):
        lh = 3.6 * mm
        lw = lh * 1706 / 309
        mark = RLImage(logo, width=lw, height=lh)
        mark.hAlign = "LEFT"
        top.append(mark)
        top.append(Spacer(1, 1.5 * mm))

    flow = []
    flow.extend(top)
    flow.append(Paragraph("ПРЕСС-КАРТА", title))
    flow.append(Paragraph("проект «Смена контента»", tiny))
    flow.append(Spacer(1, 3 * mm))
    for label in ["Фамилия, имя, отчество", "Регион / редакция", "Номер карты",
                  "Действительна до"]:
        flow.append(Paragraph(label, field))
        flow.append(HRFlowable(width="100%", thickness=0.4, color=LINE, spaceAfter=4))
    flow.append(Spacer(1, 1.2 * mm))
    flow.append(HRFlowable(width="45%", thickness=0.4, color=INK, spaceAfter=1.5))
    flow.append(Paragraph("подпись руководителя редакции", foot))
    flow.append(Spacer(1, 1.5 * mm))
    flow.append(Paragraph("Пресс-карта подтверждает сотрудничество с проектом и не является "
                          "удостоверением журналиста зарегистрированного СМИ. "
                          "%s" % SITE, foot))

    doc.build(flow)
    print("готово:", os.path.relpath(path, ROOT))


